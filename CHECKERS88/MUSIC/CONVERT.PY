#!/usr/bin/env python3
"""Mutopia Standard MIDI -> bounded eight-voice OPL events at PIT / 32768.
No runtime MIDI parser. Original converter, MIT. Score licences: SOURCES.TXT.
Requires Python 3 standard library only. Sustain pedal is replaced by FM release.
"""
from pathlib import Path
import struct, collections
HERE=Path(__file__).resolve().parent
RATE=1193182/32768

def vlq(data,pos):
    n=0
    for _ in range(4):
        v=data[pos];pos+=1;n=(n<<7)|(v&127)
        if not v&128:return n,pos
    raise ValueError('Invalid MIDI VLQ')

def read_midi(data):
    assert data[:4]==b'MThd'
    length=struct.unpack('>I',data[4:8])[0]
    fmt,tracks,division=struct.unpack('>HHH',data[8:14]);assert fmt in (0,1) and not division&32768
    pos=8+length;events=[]
    for track in range(tracks):
        assert data[pos:pos+4]==b'MTrk';size=struct.unpack('>I',data[pos+4:pos+8])[0]
        t=data[pos+8:pos+8+size];pos+=8+size;p=0;tick=0;running=None
        while p<len(t):
            dt,p=vlq(t,p);tick+=dt;status=t[p]
            if status&128:p+=1
            else:assert running is not None;status=running
            if status==255:
                typ=t[p];p+=1;n,p=vlq(t,p);payload=t[p:p+n];p+=n
                if typ==81:events.append((tick,0,'tempo',int.from_bytes(payload,'big')))
                if typ==47:events.append((tick,2,'end',0))
            elif status in (240,247):n,p=vlq(t,p);p+=n;running=None
            else:
                running=status;kind=status>>4;channel=status&15
                n=1 if kind in (12,13) else 2;v=t[p:p+n];p+=n
                if kind in (8,9):events.append((tick,1,'note',(track,channel,v[0],v[1] if kind==9 else 0)))
    events.sort(key=lambda e:(e[0],e[1]));tempo=500000;prev=0;seconds=0;out=[];end=0
    for tick,_,kind,v in events:
        seconds+=(tick-prev)*tempo/(division*1e6);prev=tick
        if kind=='tempo':tempo=v
        elif kind=='note':out.append((round(seconds*RATE),*v))
        end=max(end,round(seconds*RATE))
    return out,end

def convert(data):
    notes,end=read_midi(data);active={};slots=[None]*8;events=[];peak=0;stolen=0;count=0
    # Offs precede simultaneous ons; preserve all score notes where possible.
    notes.sort(key=lambda e:(e[0],bool(e[4]),e[1],e[3]))
    for tick,track,mch,pitch,vel in notes:
        key=(track,mch,pitch)
        if not vel:
            if key in active:
                ch=active.pop(key);slots[ch]=None;events.append((tick,ch,0,0))
            continue
        if key in active:
            ch=active.pop(key);slots[ch]=None;events.append((tick,ch,0,0))
        if None not in slots:
            # Quietest/oldest voice, but keep newly sounding melody when crowded.
            ch=min(range(8),key=lambda c:(slots[c][1],slots[c][2]));active.pop(slots[ch][0]);stolen+=1
            events.append((tick,ch,0,0))
        else:ch=slots.index(None)
        active[key]=ch;slots[ch]=(key,vel,tick);peak=max(peak,len(active));count+=1
        assert 12<=pitch<=107, pitch
        # Gentle piano-like FM. Retain relative MIDI dynamics, avoid inaudible pp.
        atten=max(1,min(24,(127-vel)//5))
        events.append((tick,ch,pitch,atten))
    for ch in range(8):events.append((end,ch,0,0))
    events.append((end+round(RATE*2),255,0,0))
    packed=[];last=0
    for tick,ch,pitch,atten in events:
        delta=tick-last;assert delta>=0
        while delta>255:packed.append((255,254,0,0));delta-=255
        packed.append((delta,ch,pitch,atten));last=tick
    burst=collections.Counter(t for t,ch,p,a in events if ch<8)
    print(f'{count} notes, {end/RATE:.1f}s, peak {peak}, stolen {stolen}, max {max(burst.values())} events/tick, {len(packed)*4} bytes')
    assert stolen==0 and max(burst.values())<=32
    return packed

def main():
    moon=(HERE/'moonlight1.mid').read_bytes()
    sources=[(HERE/'blue_danube.mid').read_bytes(),(HERE/'fur_Elise_WoO59.mid').read_bytes(),moon,(HERE/'ode.mid').read_bytes()]
    titles=['BLUE DANUBE','FUR ELISE','MOONLIGHT SONATA','ODE TO JOY']
    lines=['/* Generated by MUSIC/CONVERT.PY. Musical data: see MUSIC/SOURCES.TXT. */','typedef struct { U8 delay,ch,pitch,level; } MusicEvent;']
    for i,data in enumerate(sources):
        print(titles[i],end=': ');ev=convert(data)
        lines.append(f'static const MusicEvent tune{i}[]={{')
        for j in range(0,len(ev),8):lines.append(' '+','.join('{%d,%d,%d,%d}'%e for e in ev[j:j+8])+',')
        lines.append('};')
    lines+=['static const MusicEvent * const tunes[4]={tune0,tune1,tune2,tune3};','static const char * const tunenames[4]={'+','.join('"'+n+'"' for n in titles)+'};']
    (HERE.parent/'MUSIC.H').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
